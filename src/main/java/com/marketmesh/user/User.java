//package declaration
package com.marketmesh.user;

/*
 * User entity representing a user in the system
 * jakarta.persistence.Entity is used to mark this class as a JPA entity
 * jakarta.persistence.Table is used to specify the table name in the database
 * lombok.Data generates getters, setters, toString, equals, and hashCode methods
 * lombok.NoArgsConstructor generates a no-argument constructor
 * lombok.AllArgsConstructor generates an all-argument constructor
 * email validation is done using jakarta.validation.constraints.Email
 * not blank validation is done using jakarta.validation.constraints.NotBlank
 * localDateTime is used to store the creation timestamp of the user
 */
import jakarta.persistence.*;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.AllArgsConstructor;
import java.time.LocalDateTime;

/**
 * User entity representing a user in the system.
 * This class is annotated with JPA annotations to map it to a database table.
 * It includes fields for user details such as name, email, password, phone, role, and creation timestamp.
 */
@Entity
@Table(name = "users") //table name in the database users
@Data
@NoArgsConstructor
@AllArgsConstructor
public class User {

    // Primary key for the User entity, auto-generated by the database
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // User's name, cannot be blank
    @NotBlank
    private String name;

    // User's email, must be unique and cannot be blank, validated for proper email format
    @Email
    @NotBlank
    @Column(unique = true, nullable = false)
    private String email;

    // User's password, cannot be blank
    @NotBlank
    private String password;

    // User's phone number, optional
    private String phone;

    // User's role, stored as a string in the database, defaults to USER
    @Enumerated(EnumType.STRING)
    private Role role = Role.USER;

    private LocalDateTime createdAt = LocalDateTime.now();
}