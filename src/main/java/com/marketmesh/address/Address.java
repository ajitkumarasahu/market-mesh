package com.marketmesh.address;

/**
 * Address entity representing a user's address.
 * jarkarta.persistence.Entity is used to mark this class as a JPA entity.
 * jarkarta.persistence.Table is used to specify the table name in the database.
 * lombok.Data generates getters, setters, toString, equals, and hashCode methods.
 */
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.marketmesh.user.User;
import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.AllArgsConstructor;

/*
 * Address entity representing a user's address.
 * This class is annotated with JPA annotations to map it to a database table.
 * It includes fields for address details such as street, city, state, pincode, country, and a reference to the associated user.
 * The user field is annotated with @ManyToOne to establish a many-to-one relationship with the User entity.
 * The @JsonIgnore annotation is used to prevent serialization of the user field when converting the Address
 */
@Entity
@Table(name = "addresses")
@Data
@NoArgsConstructor
@AllArgsConstructor
public class Address {

    // Primary key for the Address entity, auto-generated by the database
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Many-to-one relationship with the User entity, fetch type is LAZY to optimize performance
     * column name in the database is user_id, cannot be null it is a foreign key referencing the User entity
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    @JsonIgnore
    private User user;

    // Address fields with validation constraints to ensure data integrity
    @NotBlank
    private String street;

    // City field, cannot be blank
    @NotBlank
    private String city;

    // State field, cannot be blank
    @NotBlank
    private String state;

    // Pincode field, cannot be blank
    @NotBlank
    private String pincode;

    // Country field, cannot be blank, defaults to "India"
    private String country = "India";

    private boolean isDefault = false;
}